import { createGitTransactionManager } from "../packages/txn-fs/src/index.ts"
/**
 * txn-fs — transactional filesystem begin/propose/commit throughput.
 *
 * Uses the in-memory backend (no real FS I/O).
 *
 * Run: bun bench txn-fs.bench.ts
 */
import { bench, run } from "./bench-utils.ts"

const mgr = createGitTransactionManager()

const FILES = Array.from({ length: 10 }, (_, i) => ({
  path: `src/file-${i}.ts`,
  content: `export const value${i} = ${i}\n// generated by benchmark\n`,
}))

const currentContent = (file: string): string => FILES.find((f) => f.path === file)!.content

bench("begin transaction (10 files)", () => {
  mgr.begin("bench", FILES)
})

bench("begin + propose + commit", () => {
  const tx = mgr.begin("bench", FILES)
  mgr.propose("src/file-0.ts", "export const value0 = 999\n// edited by benchmark\n")
  const result = mgr.commit(tx, currentContent)
  if (result.status !== "SUCCESS") throw new Error(`commit failed: ${result.status}`)
})

bench("three-way merge (no conflict)", () => {
  mgr.merge(FILES[0]!.content, FILES[0]!.content.replace("export", "const"), FILES[0]!.content)
})

await run()
